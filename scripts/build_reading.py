def pinyin_map(words, target):
    m = {}   # hsk30.json is ordered by level then sequence, so setdefault keeps the lowest-level reading
    for w in words:
        if int(w["hsk_level"][3:]) <= target:
            m.setdefault(w["simplified"], w["pinyin"])
    return m


def to_pinyin(text, words_set, pin):
    out, i, n = [], 0, len(text)
    while i < n:
        ch = text[i]
        if ch in cl.PUNCT:
            if ch not in " \n\t\r":
                out.append(ch)
            i += 1
            continue
        for L in range(min(4, n - i), 0, -1):
            seg = text[i:i + L]
            if seg in words_set:
                out.append(pin[seg]); i += L; break
        else:
            out.append(NAME_PINYIN.get(ch, ch)); i += 1
    return " ".join(out)


def main():
    levels = cl.load_levels()
    allwords = json.loads(cl.HSK.read_text(encoding="utf-8"))
    failures = 0
    for level, texts in [("HSK1", HSK1)]:
        target = int(level[3:])
        words_set, _ = cl.allowed_sets(levels, target)
        pin = pinyin_map(allwords, target)
        rows = []
        for t in texts:
            bad = cl.check(t["zh"], target, levels)
            if bad:
                failures += 1
                print(f"[{level}] {t['title']}: OUT OF LEVEL -> {[b['token'] for b in bad]}")
                continue
            rows.append({
                "title": t["title"], "title_pinyin": to_pinyin(t["title"], words_set, pin),
                "topic": t["topic"], "hsk_level": level,
                "content": t["zh"], "content_pinyin": to_pinyin(t["zh"], words_set, pin),
                "translation": t["en"], "word_count": sum(1 for c in t["zh"] if c not in cl.PUNCT),
            })
        out = OUT / f"{level.lower()}_texts.json"
        out.write_text(json.dumps(rows, ensure_ascii=False, indent=1), encoding="utf-8")
        print(f"{level}: wrote {len(rows)} texts -> {out.name}")
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    main()
